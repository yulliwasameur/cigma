from __future__ import annotations

from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "results" / "default" / "metrics" / "method_metrics.csv"
OUTPUT = ROOT / "results" / "default" / "paper_macros.tex"


def macro_name(method: str, metric: str) -> str:
    parts = [*method.split("_"), *metric.split("_")]
    return "CIGMA" + "".join(part.title().replace("-", "") for part in parts)


def main() -> None:
    frame = pd.read_csv(METRICS)
    selected = [
        "asset_f1",
        "pairwise_f1",
        "b3_f1",
        "edge_f1",
        "edge_fp_rate",
        "ndcg_at_5",
        "ndcg_at_10",
        "kendall_tau_b",
        "critical_misses",
        "verify_count",
    ]
    lines = [
        "% Generated by scripts/export_paper_macros.py.",
        "% Clean-room results: do not label these as the lost historical artifact.",
    ]
    for _, row in frame.sort_values("method").iterrows():
        for metric in selected:
            value = row[metric]
            rendered = str(int(value)) if metric in {"critical_misses", "verify_count"} else f"{float(value):.4f}"
            lines.append(f"\\newcommand{{\\{macro_name(row['method'], metric)}}}{{{rendered}}}")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUTPUT)


if __name__ == "__main__":
    main()
